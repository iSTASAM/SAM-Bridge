export type LineLoginCopy = {
  [Key in keyof (typeof LINE_LOGIN_COPY)["th"]]: string;
};

export type LineLoginUiState =
  | "loading"
  | "ready"
  | "submitting"
  | "error"
  | "linked"
  | "alreadyLinked"
  | "unavailable";

export type LineLoginErrorCode =
  | "invalid"
  | "unauthorized"
  | "suspended"
  | "lineLinkedOther"
  | "notFound";

export function lineLoginErrorMessage(copy: LineLoginCopy, code: LineLoginErrorCode): string {
  switch (code) {
    case "unauthorized":
      return copy.errorUnauthorized;
    case "suspended":
      return copy.errorSuspended;
    case "lineLinkedOther":
      return copy.errorLineLinkedOther;
    case "notFound":
      return copy.errorNotFound;
    case "invalid":
    default:
      return copy.errorGeneric;
  }
}
